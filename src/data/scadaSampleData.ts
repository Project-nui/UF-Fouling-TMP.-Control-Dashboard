// Generate next online SCADA filtration cycle point(s) following plant kinetics
export function generateNextOnlineCycle(
  current: ProcessedDataset,
  count = 1
): ProcessedDataset {
  const lastTs = current.timestamps.length > 0
    ? current.timestamps[current.timestamps.length - 1]
    : Date.now();

  const newTimestamps = [...current.timestamps];
  const newTmp = current.tmp.map(arr => [...arr]);
  const newFlow = current.flow.map(arr => [...arr]);

  const stepMs = 2.4 * 3600 * 1000; // 2 hours 24 mins

  for (let c = 0; c < count; c++) {
    const nextTs = lastTs + (c + 1) * stepMs;
    newTimestamps.push(nextTs);

    // Baseline trends for 5 units
    const baselines = [
      { tmpBase: 0.11, tmpDrift: 0.006, flowBase: 48 }, // UF-1
      { tmpBase: 0.08, tmpDrift: 0.005, flowBase: 52 }, // UF-2
      { tmpBase: 0.04, tmpDrift: 0.004, flowBase: 38 }, // UF-3
      { tmpBase: 0.035, tmpDrift: 0.005, flowBase: 44 }, // UF-4
      { tmpBase: 0.045, tmpDrift: 0.006, flowBase: 46 }  // UF-5
    ];

    for (let u = 0; u < 5; u++) {
      const b = baselines[u];
      const prevTmp = newTmp[u]?.length ? newTmp[u][newTmp[u].length - 1] ?? b.tmpBase : b.tmpBase;
      const prevFlow = newFlow[u]?.length ? newFlow[u][newFlow[u].length - 1] ?? b.flowBase : b.flowBase;

      // Realistic noise and gradual fouling increase
      const jitterTmp = (Math.random() - 0.45) * 0.008;
      let nextTmpVal = Math.round((prevTmp + b.tmpDrift * 0.4 + jitterTmp) * 10000) / 10000;

      // Prevent runaway
      if (nextTmpVal > 0.45) nextTmpVal = 0.12; // simulated backwash drop

      const jitterFlow = (Math.random() - 0.5) * 6;
      const nextFlowVal = Math.max(10, Math.round((prevFlow * 0.9 + b.flowBase * 0.1 + jitterFlow) * 100) / 100);

      newTmp[u].push(nextTmpVal);
      newFlow[u].push(nextFlowVal);
    }
  }

  return {
    timestamps: newTimestamps,
    tmp: newTmp,
    flow: newFlow,
    isEmbedded: false,
    sourceLabel: `SCADA WHA-UP (อัปเดตออนไลน์สด · ${newTimestamps.length} รอบการกรอง)`
  };
}
